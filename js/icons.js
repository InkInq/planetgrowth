function toPath(rows) {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let w = 0;
      while (row[x + w] === '#') w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(BITMAPS).map(([k, v]) => [k, toPath(v)]));

export function icon(name, cls = '') {
  return `<svg class="px ${cls}" viewBox="0 0 8 8" aria-hidden="true" shape-rendering="crispEdges"><path d="${PATHS[name]}"/></svg>`;
}

